# Build a cutie release: the release exe, the setup and a portable zip.
#
#   powershell -ExecutionPolicy Bypass -File installer\build.ps1
#
# Output lands in dist\:
#   cutie-<version>-setup.exe      installer (context menu, Start Menu, deps)
#   cutie-<version>-portable.zip   cutie.exe + README (run `cutie.exe --install`)
param(
    # Reuse target\release\cutie.exe instead of running cargo.
    [switch]$SkipBuild
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$version = (Select-String -Path Cargo.toml -Pattern '^version\s*=\s*"([^"]+)"' |
    Select-Object -First 1).Matches[0].Groups[1].Value
Write-Host "cutie $version"

if (-not $SkipBuild) {
    cargo build --release
    if ($LASTEXITCODE -ne 0) { throw "cargo build failed" }
}

# The icon is generated by build.rs into OUT_DIR; take the newest one.
$ico = Get-ChildItem target\release\build -Filter cutie.ico -Recurse |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $ico) { throw "cutie.ico not found — run without -SkipBuild" }

$dist = Join-Path $root dist
$stage = Join-Path $dist stage
Remove-Item -Recurse -Force $stage -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force $stage | Out-Null
Copy-Item target\release\cutie.exe $stage
Copy-Item $ico.FullName (Join-Path $stage cutie.ico)

$iscc = @(
    "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
    "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
    "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw "Inno Setup 6 not found — winget install JRSoftware.InnoSetup" }

& $iscc /Q "/DAppVersion=$version" "/DSrcDir=$stage" installer\cutie.iss
if ($LASTEXITCODE -ne 0) { throw "ISCC failed" }

$zip = Join-Path $dist "cutie-$version-portable.zip"
Remove-Item -Force $zip -ErrorAction SilentlyContinue
Compress-Archive -Path (Join-Path $stage cutie.exe), README.md -DestinationPath $zip

Remove-Item -Recurse -Force $stage
Get-ChildItem $dist | Select-Object Name, @{ n = 'MB'; e = { [math]::Round($_.Length / 1MB, 1) } }
