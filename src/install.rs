//! Explorer context-menu installer. Everything is written under HKCU (no
//! admin) and lives in %LOCALAPPDATA%\cutie so it can be removed cleanly.

use std::path::PathBuf;
use std::process::{Command, Stdio};

const MENU_TEXT: &str = "Download with Cutie";
/// (registry key, which command template to use)
const TARGETS: [(&str, &str); 4] = [
    (
        r"HKCU:\Software\Classes\Directory\Background\shell\cutie",
        "cmdBg",
    ),
    (r"HKCU:\Software\Classes\Directory\shell\cutie", "cmdDir"),
    (
        r"HKCU:\Software\Classes\Desktop\Background\shell\cutie",
        "cmdBg",
    ),
    (
        r"HKCU:\Software\Classes\Drive\Background\shell\cutie",
        "cmdBg",
    ),
];

/// Icon baked in at build time (generated by build.rs into OUT_DIR).
const ICON_BYTES: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/cutie.ico"));

pub fn install() -> Result<PathBuf, String> {
    let src = std::env::current_exe().map_err(|e| e.to_string())?;
    let dest_dir = app_dir();
    std::fs::create_dir_all(&dest_dir).map_err(|e| e.to_string())?;
    let dest = dest_dir.join("cutie.exe");
    if !same_file(&src, &dest) {
        std::fs::copy(&src, &dest).map_err(|e| e.to_string())?;
    }

    // shell icon beside the exe (bytes come from the binary, not the build tree)
    let ico_dest = dest_dir.join("cutie.ico");
    std::fs::write(&ico_dest, ICON_BYTES).map_err(|e| e.to_string())?;

    let exe = dest.to_string_lossy().replace('/', "\\");
    let script = install_script(&exe, &ico_dest.to_string_lossy().replace('/', "\\"));

    let out = Command::new("powershell")
        .args([
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-Command",
            &script,
        ])
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
        .map_err(|e| format!("powershell: {e}"))?;

    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        return Err(format!(
            "registry install failed: {}",
            err.lines()
                .find(|l| !l.trim().is_empty())
                .unwrap_or("unknown")
        ));
    }
    Ok(dest)
}

pub fn uninstall() {
    let script = format!(
        "$ErrorActionPreference = 'SilentlyContinue'\n\
         $keys = @({keys});\n\
         foreach ($k in $keys) {{ Remove-Item -Path $k -Recurse -Force }}\n\
         $sm = Join-Path $env:APPDATA 'Microsoft\\Windows\\Start Menu\\Programs\\cutie';\n\
         if (Test-Path $sm) {{ Remove-Item -Path $sm -Recurse -Force }}\n\
         $app = Join-Path $env:LOCALAPPDATA 'cutie';\n\
         if (Test-Path $app) {{ Remove-Item -Path $app -Recurse -Force }}\n",
        keys = TARGETS
            .iter()
            .map(|(k, _)| format!("'{k}'"))
            .collect::<Vec<_>>()
            .join(",")
    );
    let _ = Command::new("powershell")
        .args([
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-Command",
            &script,
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
}

/// The PowerShell that registers the menu entries + start-menu shortcut.
/// Single-quoted strings: only `'` needs escaping, done by doubling.
fn install_script(exe: &str, ico: &str) -> String {
    let exe_q = exe.replace('\'', "''");
    let ico_q = ico.replace('\'', "''");
    let targets = TARGETS
        .iter()
        .map(|(k, cmd)| format!("@('{k}', ${cmd})"))
        .collect::<Vec<_>>()
        .join(",\n    ");
    format!(
        "$ErrorActionPreference = 'Stop'\n\
         $exe = '{exe_q}'\n\
         $ico = '{ico_q}'\n\
         $menu = '{MENU_TEXT}'\n\
         $icon = if (Test-Path $ico) {{ '\"' + $ico + '\"' }} else {{ '\"' + $exe + '\"' }}\n\
         $cmdBg = '\"' + $exe + '\" \"%V\"'\n\
         $cmdDir = '\"' + $exe + '\" \"%1\"'\n\
         $targets = @(\n    {targets}\n  )\n\
         foreach ($t in $targets) {{\n\
           $key = $t[0]; $cmd = $t[1]\n\
           New-Item -Path $key -Force | Out-Null\n\
           Set-ItemProperty -Path $key -Name '(default)' -Value $menu\n\
           Set-ItemProperty -Path $key -Name 'Icon' -Value $icon -Type String\n\
           Set-ItemProperty -Path $key -Name 'MUIVerb' -Value $menu -Type String\n\
           $ckey = $key + '\\command'\n\
           New-Item -Path $ckey -Force | Out-Null\n\
           Set-ItemProperty -Path $ckey -Name '(default)' -Value $cmd\n\
         }}\n\
         $sm = Join-Path $env:APPDATA 'Microsoft\\Windows\\Start Menu\\Programs\\cutie'\n\
         New-Item -ItemType Directory -Path $sm -Force | Out-Null\n\
         $w = New-Object -ComObject WScript.Shell\n\
         $l = $w.CreateShortcut((Join-Path $sm 'cutie.lnk'))\n\
         $l.TargetPath = $exe\n\
         $l.WorkingDirectory = $exe\n\
         $l.Description = 'cutie video downloader'\n\
         $l.Save()\n\
         Write-Output 'OK'\n"
    )
}

/// Different paths, but also "the same file" via 8.3 short names / hardlinks.
fn same_file(a: &std::path::Path, b: &std::path::Path) -> bool {
    if a == b {
        return true;
    }
    match (std::fs::canonicalize(a), std::fs::canonicalize(b)) {
        (Ok(x), Ok(y)) => x == y,
        _ => false,
    }
}

fn app_dir() -> PathBuf {
    let base = std::env::var("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("."));
    base.join("cutie")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn script_escapes_and_references_every_key() {
        let s = install_script("C:\\Users\\o'brien\\cutie.exe", "C:\\x\\cutie.ico");
        assert!(s.contains("o''brien"), "single quotes must be doubled");
        assert!(s.contains("cutie.ico"));
        for (k, cmd) in TARGETS {
            assert!(s.contains(k), "missing registry key {k}");
            assert!(s.contains(&format!("${cmd}")), "missing command {cmd}");
        }
        assert!(s.contains("%V") && s.contains("%1"));
    }

    #[test]
    fn icon_bytes_are_a_real_ico() {
        assert_eq!(&ICON_BYTES[..4], &[0, 0, 1, 0]);
    }

    #[test]
    fn same_file_detects_identity() {
        let d = default_temp();
        assert!(same_file(&d, &d));
        assert!(!same_file(&d, &d.parent().unwrap().join("nope-nope")));
    }

    fn default_temp() -> PathBuf {
        std::env::temp_dir()
    }
}
